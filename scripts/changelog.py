#!/usr/bin/env python3
"""Generate CHANGELOG.md from the reviewed, structured change record."""

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = {"version", "status", "added", "pending_acceptance"}


def unique_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate field: {key}")
        result[key] = value
    return result


def version_key(version: str) -> tuple:
    """Validate SemVer and sort numeric/prerelease components by precedence."""
    match = re.fullmatch(
        r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)"
        r"(?:-([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?"
        r"(?:\+([0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*))?",
        version,
    )
    if not match:
        raise ValueError(f"invalid semantic version: {version}")
    major, minor, patch, prerelease, _ = match.groups()
    identifiers = prerelease.split(".") if prerelease else []
    if any(v.isdigit() and len(v) > 1 and v.startswith("0") for v in identifiers):
        raise ValueError(f"leading zero in prerelease: {version}")
    parts = tuple((0, int(v)) if v.isdigit() else (1, v) for v in identifiers)
    return int(major), int(minor), int(patch), not prerelease, parts, version


def render_record(source: Path) -> str:
    record = json.loads(
        source.read_text(encoding="utf-8"), object_pairs_hook=unique_object
    )
    if not isinstance(record, dict) or set(record) != FIELDS:
        raise ValueError(
            "source must contain exactly version, status, added, pending_acceptance"
        )
    version = record["version"]
    if not isinstance(version, str) or version != source.stem:
        raise ValueError(f"version must match source filename: {source.name}")
    version_key(version)
    status = record["status"]
    if status == "unreleased":
        status = "Unreleased"
    elif isinstance(status, str) and re.fullmatch(
        r"[0-9]{4}-[0-9]{2}-[0-9]{2}", status
    ):
        date.fromisoformat(status)
    else:
        raise ValueError("status must be unreleased or an ISO date (YYYY-MM-DD)")
    lines = [f"## {version} - {status}", ""]
    for field, title in (
        ("added", "Added"),
        ("pending_acceptance", "Pending acceptance"),
    ):
        entries = record[field]
        if not isinstance(entries, list):
            raise ValueError(f"{field} must be a list of sentences")
        if not entries:
            continue
        lines.extend((f"### {title}", ""))
        for entry in entries:
            if (
                not isinstance(entry, str)
                or not entry.strip()
                or entry != entry.strip()
                or any(ord(char) < 32 or ord(char) == 127 for char in entry)
            ):
                raise ValueError(
                    f"{field} entries must be nonempty single-line text without surrounding whitespace"
                )
            lines.append(f"- {entry}")
        lines.append("")
    return "\n".join(lines)


def render(source: Path) -> str:
    files = list(source.glob("*.json")) if source.is_dir() else [source]
    if not files:
        raise ValueError("source directory contains no JSON change records")
    records = [
        render_record(path)
        for path in sorted(files, key=lambda p: version_key(p.stem), reverse=True)
    ]
    return (
        "<!-- Generated by scripts/changelog.py; edit docs/changes/*.json instead. -->\n"
        "# Changelog\n\n" + "\n".join(records)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if generated output is missing or differs; never write",
    )
    parser.add_argument("--source", type=Path, default=ROOT / "docs/changes")
    parser.add_argument("--output", type=Path, default=ROOT / "CHANGELOG.md")
    args = parser.parse_args()
    try:
        expected = render(args.source).encode("utf-8")
        if args.check:
            if not args.output.exists() or args.output.read_bytes() != expected:
                print(
                    "changelog is missing or stale; run scripts/changelog.py",
                    file=sys.stderr,
                )
                return 1
            print("changelog is current")
        else:
            if args.source.resolve() == args.output.resolve():
                raise ValueError("source and output paths must differ")
            args.output.write_bytes(expected)
            print(f"generated {args.output}")
    except (OSError, ValueError) as error:
        print(f"changelog: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
